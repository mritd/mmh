package cmd

import (
	"bytes"
	"fmt"
	"io/ioutil"
	"os"
	"path/filepath"
	"strings"

	"github.com/mitchellh/go-homedir"
	"github.com/mritd/mmh/common"
	"github.com/mritd/mmh/core"
	"github.com/spf13/cobra"
)

// completionShells are the shells supported by the completion command
var completionShells = []string{"bash", "zsh", "fish", "powershell"}

var completionCmd = &cobra.Command{
	Use:   "completion [bash|zsh|fish|powershell]",
	Short: "Generate shell completion script",
	Long: `Generate the autocompletion script for the specified shell.

The script is printed to stdout. Use the "install" subcommand to write it into
the default completion directory of the shell instead.`,
	Example: `  mmh completion zsh              # print the zsh completion script
  mmh completion install          # install completion for the current shell
  mmh completion install bash     # install completion for bash`,
	Args:      cobra.MatchAll(cobra.MaximumNArgs(1), cobra.OnlyValidArgs),
	ValidArgs: completionShells,
	Run: func(cmd *cobra.Command, args []string) {
		if len(args) == 0 {
			_ = cmd.Help()
			return
		}
		script, err := genCompletion(rootCmd, args[0])
		common.CheckAndExit(err)
		fmt.Print(script)
	},
}

var completionInstallCmd = &cobra.Command{
	Use:   "install [bash|zsh|fish]",
	Short: "Install shell completion into the default directory",
	Long: `Install the completion script into the directory which is loaded by the shell automatically.

The current shell is detected from $SHELL when no shell is given. The mcp, mcs,
mcx, mec, mgo, mping and mtun aliases are registered for completion as well.`,
	Args:      cobra.MatchAll(cobra.MaximumNArgs(1), cobra.OnlyValidArgs),
	ValidArgs: completionShells,
	Run: func(cmd *cobra.Command, args []string) {
		shell := ""
		if len(args) > 0 {
			shell = args[0]
		}
		installCompletion(shell)
	},
}

func init() {
	// replace the completion command generated by cobra
	rootCmd.CompletionOptions.DisableDefaultCmd = true
	completionCmd.AddCommand(completionInstallCmd)
	rootCmd.AddCommand(completionCmd)
}

// genCompletion generates the completion script of the given shell
func genCompletion(cmd *cobra.Command, shell string) (string, error) {
	var buf bytes.Buffer
	var err error
	switch shell {
	case "bash":
		err = cmd.GenBashCompletion(&buf)
	case "zsh":
		err = cmd.GenZshCompletion(&buf)
	case "fish":
		err = cmd.GenFishCompletion(&buf, true)
	case "powershell":
		err = cmd.GenPowerShellCompletionWithDesc(&buf)
	default:
		return "", fmt.Errorf("unsupported shell [%s], supported shells: %s", shell, strings.Join(completionShells, ", "))
	}
	if err != nil {
		return "", err
	}
	return buf.String(), nil
}

// completionInstallPath returns the completion file which is loaded by the
// given shell automatically
func completionInstallPath(shell string) (string, error) {
	home, err := homedir.Dir()
	if err != nil {
		return "", err
	}

	switch shell {
	case "zsh":
		// oh-my-zsh adds $ZSH_CUSTOM/completions to fpath automatically
		if dir := os.Getenv("ZSH_CUSTOM"); dir != "" {
			return filepath.Join(dir, "completions", "_mmh"), nil
		}
		if dir := os.Getenv("ZSH"); dir != "" {
			return filepath.Join(dir, "custom", "completions", "_mmh"), nil
		}
		return filepath.Join(home, ".zsh", "completions", "_mmh"), nil
	case "bash":
		return filepath.Join(xdgDataHome(home), "bash-completion", "completions", "mmh"), nil
	case "fish":
		return filepath.Join(xdgConfigHome(home), "fish", "completions", "mmh.fish"), nil
	default:
		return "", fmt.Errorf("completion install is not supported for [%s], run `mmh completion %s` and load the script manually", shell, shell)
	}
}

// installCompletion writes the completion script into the shell's default
// completion directory
func installCompletion(shell string) {
	if shell == "" {
		shell = core.DetectShell()
	}
	if shell == "sh" {
		common.Exit("failed to detect the current shell, please specify one of: bash, zsh, fish", 1)
	}

	path, err := completionInstallPath(shell)
	common.CheckAndExit(err)
	script, err := genCompletion(rootCmd, shell)
	common.CheckAndExit(err)
	script = registerAliasCompletion(shell, script)

	common.CheckAndExit(os.MkdirAll(filepath.Dir(path), 0755))
	common.CheckAndExit(ioutil.WriteFile(path, []byte(script), 0644))

	fmt.Printf("✅ %s completion installed to %s\n", shell, path)
	switch {
	case shell == "zsh" && os.Getenv("ZSH_CUSTOM") == "" && os.Getenv("ZSH") == "":
		fmt.Printf("   add `fpath+=(%s)` to ~/.zshrc if it is not in $fpath\n", filepath.Dir(path))
	case shell == "bash":
		fmt.Println("   bash-completion >= 2.0 is required to load this file automatically")
	}
}

// registerAliasCompletion registers the mmh subcommand aliases so they complete
// like the mmh command itself
func registerAliasCompletion(shell, script string) string {
	script = ensureTrailingNewline(script)
	names := strings.Join(core.AliasNames, " ")

	switch shell {
	case "zsh":
		return script + "compdef _mmh " + names + "\n"
	case "bash":
		return script + "complete -o default -o nospace -F __start_mmh " + names + "\n"
	case "fish":
		var b strings.Builder
		b.WriteString(script)
		for _, name := range core.AliasNames {
			fmt.Fprintf(&b, "complete -c %s -w mmh\n", name)
		}
		return b.String()
	}
	return script
}

func ensureTrailingNewline(script string) string {
	if script != "" && !strings.HasSuffix(script, "\n") {
		return script + "\n"
	}
	return script
}

func xdgDataHome(home string) string {
	if dir := os.Getenv("XDG_DATA_HOME"); dir != "" {
		return dir
	}
	return filepath.Join(home, ".local", "share")
}

func xdgConfigHome(home string) string {
	if dir := os.Getenv("XDG_CONFIG_HOME"); dir != "" {
		return dir
	}
	return filepath.Join(home, ".config")
}
